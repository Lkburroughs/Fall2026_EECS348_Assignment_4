// ============================================================================
// Class SudokuGrid (Code Block Generated by Claude): owns the 9x9 board and knows how to load, print, and
//                    check legality of placements. It has no solving logic.
// ============================================================================
class SudokuGrid {
public:                                              // public interface for SudokuGrid
    static const int SIZE = 9;                       // the board is 9 by 9
    static const int BOX = 3;                        // sub grids in the board are 3 by 3

    SudokuGrid() {                                   // default constructor
        for (int r = 0; r < SIZE; r++) {             // loop over every row
            for (int c = 0; c < SIZE; c++) {         // loop over every column
                cells[r][c] = 0;                     // 0 means the cell is empty
            }                                        // end column loop
        }                                            // end row loop
    }                                                // end constructor

    bool loadFromFile(const std::string& fileName) { // read a puzzle from a text file
        std::ifstream in(fileName);                  // open the file for reading
        if (!in) {                                   // check if file is opened
            return false;                            // report failure to the caller
        }                                            // end if
        int count = 0;                               // no cells have been read yet
        char ch;                                     //  variable for the character currently read
        while (count < SIZE * SIZE && in.get(ch)) {  // read until 81 cells or EOF
            if (ch >= '1' && ch <= '9') {            // a digit 1-9 is a given value
                cells[count / SIZE][count % SIZE] = ch - '0'; // store its numeric value
                count++;                             // move on to the next cell
            } else if (ch == '_' || ch == '0' || ch == '.') { // mark blank cells with 0
                cells[count / SIZE][count % SIZE] = 0; // store 0 for an empty cell
                count++;                             // move on to the next cell
            }                                        // ignore any other characters (spaces, newlines, etc.)
        }                                            // end while
        return count == SIZE * SIZE;                 // true if exactly 81 cells were read, false otherwise
    }                                                // end loadFromFile

    void print() const {                             // print the board to the console
        for (int r = 0; r < SIZE; r++) {             // loop over every row
            if (r % BOX == 0 && r != 0) {            // between block rows...
                std::cout << "------+-------+------\n"; // ...draw a horizontal divider
            }                                        // end if
            for (int c = 0; c < SIZE; c++) {         // loop over every column
                if (c % BOX == 0 && c != 0) {        // between block columns...
                    std::cout << "| ";               // ...draw a vertical divider
                }                                    // end if
                if (cells[r][c] == 0) {              // check if the cell is empty
                    std::cout << "_ ";               // show an underscore
                } else {                             // filled cell
                    std::cout << cells[r][c] << " "; // show its digit
                }                                    // end if/else
            }                                        // end column loop
            std::cout << "\n";                       // end the printed row
        }                                            // end row loop
    }                                                // end print

    int get(int r, int c) const {                    // read the value of a cell
        return cells[r][c];                          // return the stored value (0 if empty)
    }                                                // end get

    void set(int r, int c, int value) {              // write a value to a cell (0 clears it)
        cells[r][c] = value;                         // store the value
    }                                                // end set

    bool findEmptyCell(int& row, int& col) const {   // locate the next empty cell (0) and hand back its coordinates
        for (int r = 0; r < SIZE; r++) {             // scan rows top to bottom
            for (int c = 0; c < SIZE; c++) {         // scan columns left to right
                if (cells[r][c] == 0) {              // an empty cell found
                    row = r;                         // return its row
                    col = c;                         // return its column
                    return true;                     // indicate that an empty cell was found
                }                                    // end if
            }                                        // end column loop
        }                                            // end row loop
        return false;                                // no empty cells found
    }                                                // end findEmptyCell

    bool canPlace(int r, int c, int value) const {   // check if a value can be legally placed in a cell
        for (int i = 0; i < SIZE; i++) {             // loop over every cell in the same row and column
            if (cells[r][i] == value) return false;  // value already in this row
            if (cells[i][c] == value) return false;  // value already in this column
        }                                            // end loop
        int boxR = (r / BOX) * BOX;                  // top row of the 3x3 block
        int boxC = (c / BOX) * BOX;                  // left column of the 3x3 block
        for (int i = 0; i < BOX; i++) {              // loop over block rows
            for (int j = 0; j < BOX; j++) {          // loop over block columns
                if (cells[boxR + i][boxC + j] == value) return false; // value already in this 3x3 block
            }                                        // end inner loop
        }                                            // end outer loop
        return true;                                 // no conflicts found, placement is legal
    }                                                // end canPlace

    std::vector<int> candidates(int r, int c) const {// return a list of legal digits for a given empty cell
        std::vector<int> result;                     // vector to hold the candidates
        for (int v = 1; v <= SIZE; v++) {            // try every digit from 1 to 9
            if (canPlace(r, c, v)) {                 // if the digit can be placed here
                result.push_back(v);                 // add it to the list of candidates
            }                                        // end if
        }                                            // end for
        return result;                               // return the list of candidates
    }                                                // end candidates

    bool givensAreConsistent() const {               // check if the initial clues in the puzzle are consistent (no conflicts)
        SudokuGrid copy = *this;                     // make a copy of the current grid to test placements
        for (int r = 0; r < SIZE; r++) {             // loop over every row
            for (int c = 0; c < SIZE; c++) {         // loop over every column
                int v = copy.cells[r][c];            // get the value in this cell
                if (v != 0) {                        // if it's a given clue (not empty)
                    copy.cells[r][c] = 0;            // temporarily clear the cell to test legality
                    if (!copy.canPlace(r, c, v)) {   // check if placing the value back would violate Sudoku rules
                        return false;                // yes: the puzzle is invalid (contradictory clues)
                    }                                // end inner if
                    copy.cells[r][c] = v;            // put the value back
                }                                    // end if
            }                                        // end column loop
        }                                            // end row loop
        return true;                                 // all clues are consistent, no conflicts found
    }                                                // end givensAreConsistent

private:                                             // internal data for SudokuGrid
    int cells[SIZE][SIZE];                           // the 9x9 board (0 = empty, 1-9 = filled)
};                                                   // end class SudokuGrid

// ============================================================================
// Class SudokuSolver (Code Block Generated by Claude): performs depth-first search with backtracking on a
//                      SudokuGrid and prints every solution it finds.
// ============================================================================
class SudokuSolver {
public:                                              // public interface of the class
    explicit SudokuSolver(SudokuGrid& g)             // ptr to the grid to solve
        : grid(g), solutionCount(0) {}               // initialize the grid reference and solution counter

    int solveAll() {                                 // look for all solutions to the puzzle
        solutionCount = 0;                           // reset the solution counter
        if (!grid.givensAreConsistent()) {           // check if the initial clues are valid
            return 0;                                // no solutions possible if the givens are inconsistent
        }                                            // end if
        search();                                    // start the recursive backtracking search for solutions
        return solutionCount;                        // return the total number of solutions found
    }                                                // end solveAll

private:                                             // internal data and methods for SudokuSolver
    void search() {                                  // recursive backtracking search for solutions
        int row = 0, col = 0;                        // variables to hold the coordinates of the next empty cell
        if (!grid.findEmptyCell(row, col)) {         // if no empty cell is found, the puzzle is solved
            solutionCount++;                         // increment the solution counter
            std::cout << "Solution " << solutionCount << ":\n"; // print the solution number
            grid.print();                            // print the solved grid
            std::cout << "\n";                       // blank line after the solution
            return;                                  // back up to look for more solutions
        }                                            // end if
        std::vector<int> options = grid.candidates(row, col); // get the list of legal candidates for this empty cell
        for (size_t i = 0; i < options.size(); i++) {// test each candidate in turn
            grid.set(row, col, options[i]);          // place the candidate in the cell
            search();                                // recurse to continue solving with this placement
            grid.set(row, col, 0);                   // backtrack by clearing the cell after returning from recursion
        }                                            // end for (no candidates => just returns and backtracks)
    }                                                // end search

    SudokuGrid& grid;                                // reference to the SudokuGrid being solved
    int solutionCount;                               // counter for the number of solutions found
};                                                   // end class SudokuSolver

// ============================================================================
// Class PuzzleRunner (Code Block Generated by Claude) : handles one puzzle file from loading through reporting.
// ============================================================================
class PuzzleRunner {
public:                                              // public interface for PuzzleRunner
    explicit PuzzleRunner(const std::string& name)   // constructor that takes the puzzle file name
        : fileName(name) {}                          // remember the file name

    void run() {                                     // process the puzzle file: load, solve, and report
        std::cout << "==============================\n"; // print a separator line
        std::cout << "File: " << fileName << "\n\n";  // print the puzzle file name
        SudokuGrid grid;                             // make a new SudokuGrid to hold the puzzle
        if (!grid.loadFromFile(fileName)) {          // try to read the puzzle from the file
            std::cout << "Could not read a valid puzzle from this file.\n\n"; // report error
            return;                                  // stop processing this puzzle if loading failed
        }                                            // end if
        std::cout << "Puzzle:\n";                    // print a heading for the original puzzle
        grid.print();                                // print the loaded puzzle grid
        std::cout << "\n";                           // blank line
        SudokuSolver solver(grid);                   // create a solver for this grid
        int found = solver.solveAll();               // find all solutions and get the count of solutions found
        if (found == 0) {                            // no solutions were found
            std::cout << "No solution found\n\n";    // required output when no solution exists
        } else {                                     // at least one solution was found
            std::cout << "Total solutions: " << found << "\n\n"; // summary of how many solutions were found
        }                                            // end if/else
    }                                                // end run

private:                                             // internal data
    std::string fileName;                            // path of the puzzle file
};                                                   // end class PuzzleRunner

