int main() {                                         // program entry point
    for (int i = 1; i <= 5; i++) {                   // loop over the five puzzle files
        PuzzleRunner runner("puzzle" + std::to_string(i) + ".txt"); // create a PuzzleRunner for each puzzle file
        runner.run();                                // process that puzzle
    }                                                // end for
    return 0;                                        // successful exit
}                                                    // end main